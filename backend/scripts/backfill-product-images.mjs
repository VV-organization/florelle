#!/usr/bin/env node
// One-off backfill: about 30 species in seed-data.json have an empty
// imageUrl. For each of those, pick a random imageUrl from another
// product in the SAME category (same flower type), so the placeholder
// at least matches the kind of flower the user is looking at.
//
// Output:
//   1. Rewrites seed-data.json in place — every product now has a
//      non-empty imageUrl, so future re-seeds keep the fix.
//   2. Writes scripts/backfill-product-images.sql — idempotent UPDATE
//      statements that can be piped into psql on the prod box to fix
//      rows that were already inserted by the previous seed.
//
// Determinism: we use a tiny seedable RNG so re-running this script on
// the same input always produces the same mapping. Helpful when the
// SQL needs to be regenerated and you don't want a different shuffle.
//
// Usage:
//   node scripts/backfill-product-images.mjs

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const seedPath = path.resolve(__dirname, '..', 'seed-data.json')
const sqlPath = path.resolve(__dirname, 'backfill-product-images.sql')

const seed = JSON.parse(fs.readFileSync(seedPath, 'utf8'))

// Tiny LCG seeded RNG so the assignment is reproducible.
function makeRng(seed) {
  let state = seed >>> 0
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0
    return state / 0xffffffff
  }
}

// Group all products that already have an imageUrl by category, so we
// can pull a same-category replacement first.
const byCategory = new Map()
for (const p of seed.products) {
  if (p.imageUrl && p.imageUrl.trim() !== '') {
    const list = byCategory.get(p.categorySourceId) ?? []
    list.push(p.imageUrl)
    byCategory.set(p.categorySourceId, list)
  }
}

// Global pool as the safety net for products whose category has no
// other entries with images (shouldn't happen with this seed, but
// guard against it anyway).
const globalPool = seed.products
  .filter((p) => p.imageUrl && p.imageUrl.trim() !== '')
  .map((p) => p.imageUrl)

// Walk in sorted specieId order so the script is fully deterministic.
const empty = seed.products
  .filter((p) => !p.imageUrl || p.imageUrl.trim() === '')
  .sort((a, b) => a.specieId - b.specieId)

const sqlLines = [
  '-- Auto-generated by scripts/backfill-product-images.mjs',
  '-- Backfills products.image_url for ~30 species whose seed row had an',
  '-- empty imageUrl, by reusing a random image from the same category.',
  '-- Idempotent: only updates rows that are still empty.',
  '',
  'BEGIN;',
  '',
]

const assignments = []

for (const p of empty) {
  const pool = byCategory.get(p.categorySourceId) ?? globalPool
  // Seed the RNG with the specieId so each product picks deterministically.
  const rng = makeRng(p.specieId)
  // Sort the pool to make the order independent of insertion order.
  const sorted = [...pool].sort()
  const idx = Math.floor(rng() * sorted.length)
  const chosen = sorted[idx]

  // Mutate the seed in place.
  p.imageUrl = chosen

  assignments.push({ specieId: p.specieId, name: p.name, imageUrl: chosen })

  // Escape single quotes for SQL by doubling them.
  const safeUrl = chosen.replace(/'/g, "''")
  // The seed loader uses `images.species.{sourceId}` for product image keys
  // — but the products table itself stores the URL directly in image_url.
  // We can't match by specieId (it's not in the table); we match by slug
  // which IS unique in the seed.
  const safeSlug = p.slug.replace(/'/g, "''")
  sqlLines.push(
    `UPDATE products SET image_url = '${safeUrl}' WHERE slug = '${safeSlug}' AND (image_url IS NULL OR image_url = '');`,
  )
}

sqlLines.push('', 'COMMIT;', '')

fs.writeFileSync(seedPath, JSON.stringify(seed, null, 2) + '\n')
fs.writeFileSync(sqlPath, sqlLines.join('\n'))

process.stdout.write(`Updated ${empty.length} products in seed-data.json\n`)
process.stdout.write(`Wrote SQL to ${path.relative(process.cwd(), sqlPath)}\n\n`)
process.stdout.write('Assignments:\n')
for (const a of assignments) {
  process.stdout.write(
    `  ${a.specieId.toString().padStart(6)}  ${a.name.padEnd(24)}  ${a.imageUrl}\n`,
  )
}
